/**
 * Attribution, generated from the source registry and the entries: every
 * cited source with its citation, every image with its credit and license,
 * and every contributor. ATTRIBUTION.md and the About page both come from here.
 */
import type { BuildData } from './build-data';
import { renderCitation } from './citation';
import type { PlantData, VocabValue } from './types';

export interface Attribution {
  sources: { id: string; name: string; publisher: string; url?: string; license: string; restriction?: string; citation: string; entries: number }[];
  images: { file: string; entry: string; credit: string; license: string; licenseLabel: string; licenseUrl?: string; sourceUrl?: string; nonCommercial: boolean }[];
  contributors: string[];
}

export function attribution(data: BuildData): Attribution {
  const { sources: registry, vocab } = data.library.config;
  const licenses = new Map((vocab.license as VocabValue[]).map((l) => [l.id, l]));
  const used = new Map<string, { count: number; latest: string }>();
  const images: Attribution['images'] = [];
  const contributors = new Set<string>();
  for (const b of data.entries) {
    if (b.entry.type === 'plant') {
      const d = b.entry.data as unknown as PlantData;
      for (const c of d.sources) {
        const u = used.get(c.source) ?? { count: 0, latest: '' };
        u.count++;
        if (c.accessed > u.latest) u.latest = c.accessed;
        used.set(c.source, u);
        if (c.contributor) contributors.add(c.contributor.name);
      }
      for (const img of d.images ?? []) {
        const l = licenses.get(img.license);
        images.push({ file: img.file, entry: b.key, credit: img.credit, license: img.license, licenseLabel: l?.label ?? img.license, licenseUrl: l?.url as string | undefined, sourceUrl: img.sourceUrl, nonCommercial: Boolean(l?.nonCommercial) });
      }
    }
    for (const n of b.entry.fieldNotes ?? []) contributors.add(n.author.name);
  }
  const sources = [...used.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([id, u]) => {
      const s = registry[id];
      return { id, name: s.name, publisher: s.publisher, url: s.url, license: s.license, restriction: s.restriction, citation: renderCitation(s, { source: id, accessed: u.latest, fields: [] }), entries: u.count };
    });
  return { sources, images: images.sort((a, b) => a.file.localeCompare(b.file)), contributors: [...contributors].sort() };
}

export function attributionMarkdown(a: Attribution): string {
  const lines = [
    '# Attribution',
    '',
    '<!-- Generated by `npm run attribution` from config/sources.json and the entries. Do not edit by hand. -->',
    '',
    "This repository's own compilation and prose are under CC BY 4.0 ([LICENSE-CONTENT](LICENSE-CONTENT)); its code is under the MIT license ([LICENSE](LICENSE)). Facts are recorded from the sources below in our own schema and words. Images keep their own licenses.",
    '',
    '## Sources',
    '',
  ];
  if (!a.sources.length) lines.push('No entry cites a source yet.', '');
  for (const s of a.sources) {
    lines.push(`- **${s.name}** (${s.publisher})${s.restriction ? ` — restricted: ${s.restriction}` : ''}. Cited by ${s.entries} ${s.entries === 1 ? 'entry' : 'entries'}. ${s.citation}`);
  }
  if (a.sources.length) lines.push('');
  lines.push('## Images', '');
  if (!a.images.length) lines.push('No images yet.', '');
  for (const i of a.images) {
    lines.push(`- \`${i.file}\` (${i.entry}): ${i.credit}, ${i.licenseUrl ? `[${i.licenseLabel}](${i.licenseUrl})` : i.licenseLabel}${i.sourceUrl ? `, [source](${i.sourceUrl})` : ''}${i.nonCommercial ? ' — non-commercial' : ''}`);
  }
  if (a.images.length) lines.push('');
  lines.push('## Contributors', '');
  lines.push(a.contributors.length ? a.contributors.join(', ') : 'No contributions yet.', '');
  return lines.join('\n');
}
